/** WebAudio engine: music with crossfades, voice lines (ducking music), positional SFX and ambience. */

export interface Manifest {
  voices: Record<string, { file: string; speaker: string; text: string }>;
  barks: Record<string, string[]>;
  sfx: Record<string, string[]>;
  music: Record<string, string>;
  credits?: { asset: string; source: string; license: string; url?: string; authors?: string[] }[];
}

const BASE = `${import.meta.env.BASE_URL}assets/`;

export class Audio {
  ctx: AudioContext | null = null;
  private master!: GainNode;
  private musicBus!: GainNode;
  private voiceBus!: GainNode;
  private sfxBus!: GainNode;
  private ambBus!: GainNode;
  manifest: Manifest = { voices: {}, barks: {}, sfx: {}, music: {} };
  private buffers = new Map<string, Promise<AudioBuffer | null>>();
  private musicNode: { src: AudioBufferSourceNode; gain: GainNode; key: string } | null = null;
  private voiceNode: AudioBufferSourceNode | null = null;
  private loops = new Map<string, { src: AudioBufferSourceNode; gain: GainNode }>();
  vol = { master: 0.8, music: 0.5, voice: 0.9, sfx: 0.7, ambient: 0.6 };
  muted = (() => {
    try {
      return localStorage.getItem('bc_muted') === '1';
    } catch {
      return false;
    }
  })();
  /** mute or unmute everything; remembered between visits */
  setMuted(m: boolean): void {
    this.muted = m;
    try {
      localStorage.setItem('bc_muted', m ? '1' : '0');
    } catch {
      /* ignore */
    }
    this.applyVolumes();
  }
  private lastPlay = new Map<string, number>();
  onVoice: ((speaking: boolean) => void) | null = null;
  private playlist: string[] = [];
  private musicMood: 'menu' | 'island' | 'tension' = 'menu';

  async init(): Promise<void> {
    // manifest is bundled when present (generated by the audio pipeline)
    const found = import.meta.glob('./manifest.json', { eager: true, import: 'default' }) as Record<string, Manifest>;
    const m = Object.values(found)[0];
    if (m) this.manifest = Object.assign({ voices: {}, barks: {}, sfx: {}, music: {} }, m);
    try {
      const saved = JSON.parse(localStorage.getItem('bc_audio') ?? 'null');
      if (saved) Object.assign(this.vol, saved);
    } catch {
      /* ignore */
    }
  }

  /** must be called from a user gesture */
  unlock(): void {
    if (this.ctx) {
      if (this.ctx.state === 'suspended') this.ctx.resume();
      return;
    }
    const AC = window.AudioContext || (window as any).webkitAudioContext;
    if (!AC) return;
    this.ctx = new AC();
    const c = this.ctx;
    this.master = c.createGain();
    this.master.connect(c.destination);
    this.musicBus = c.createGain();
    this.voiceBus = c.createGain();
    this.sfxBus = c.createGain();
    this.ambBus = c.createGain();
    for (const b of [this.musicBus, this.voiceBus, this.sfxBus, this.ambBus]) b.connect(this.master);
    this.applyVolumes();
    this.setMood(this.musicMood, true);
  }

  applyVolumes(): void {
    try {
      localStorage.setItem('bc_audio', JSON.stringify(this.vol));
    } catch {
      /* ignore */
    }
    if (!this.ctx) return;
    const t = this.ctx.currentTime;
    this.master.gain.setTargetAtTime(this.muted ? 0 : this.vol.master, t, 0.05);
    this.musicBus.gain.setTargetAtTime(this.vol.music * (this.voiceNode ? 0.45 : 1), t, 0.2);
    this.voiceBus.gain.setTargetAtTime(this.vol.voice, t, 0.05);
    this.sfxBus.gain.setTargetAtTime(this.vol.sfx, t, 0.05);
    this.ambBus.gain.setTargetAtTime(this.vol.ambient, t, 0.05);
  }

  private load(file: string): Promise<AudioBuffer | null> {
    let p = this.buffers.get(file);
    if (!p) {
      p = fetch(BASE + file)
        .then((r) => (r.ok ? r.arrayBuffer() : Promise.reject(r.status)))
        .then((ab) => this.ctx!.decodeAudioData(ab))
        .catch(() => null);
      this.buffers.set(file, p);
    }
    return p;
  }

  // ------------------------------------------------------------------------------------------- music
  setMood(mood: 'menu' | 'island' | 'tension', force = false): void {
    if (mood === this.musicMood && !force && this.musicNode) return;
    this.musicMood = mood;
    const m = this.manifest.music;
    if (mood === 'menu') this.playlist = ['theme'];
    else if (mood === 'tension') this.playlist = ['tension'];
    else this.playlist = ['island_1', 'island_2', 'island_3'].filter((k) => m[k]).sort(() => Math.random() - 0.5);
    this.nextTrack();
  }

  private async nextTrack(): Promise<void> {
    if (!this.ctx) return;
    const key = this.playlist.shift();
    if (!key) return;
    if (this.musicMood === 'island') this.playlist.push(key);
    const file = this.manifest.music[key];
    if (!file) return;
    const buf = await this.load(file);
    if (!buf || !this.ctx) return;
    const c = this.ctx;
    const gain = c.createGain();
    gain.gain.value = 0;
    gain.connect(this.musicBus);
    const src = c.createBufferSource();
    src.buffer = buf;
    src.loop = this.musicMood !== 'island';
    src.connect(gain);
    src.start();
    gain.gain.setTargetAtTime(1, c.currentTime, 1.2);
    const old = this.musicNode;
    if (old) {
      old.gain.gain.setTargetAtTime(0, c.currentTime, 0.8);
      setTimeout(() => old.src.stop(), 4000);
    }
    this.musicNode = { src, gain, key };
    if (!src.loop) src.onended = () => this.musicNode?.src === src && this.nextTrack();
  }

  sting(key: 'victory' | 'defeat'): void {
    const f = this.manifest.music[key];
    if (f) this.playFile(f, this.musicBus, 1);
  }

  // ------------------------------------------------------------------------------------------- voice
  async voice(key: string): Promise<string | null> {
    const v = this.manifest.voices[key];
    if (!v || !this.ctx) return v?.text ?? null;
    const buf = await this.load(v.file);
    if (!buf || !this.ctx) return v.text;
    this.voiceNode?.stop();
    const src = this.ctx.createBufferSource();
    src.buffer = buf;
    src.connect(this.voiceBus);
    src.start();
    this.voiceNode = src;
    this.onVoice?.(true);
    this.applyVolumes();
    src.onended = () => {
      if (this.voiceNode === src) {
        this.voiceNode = null;
        this.onVoice?.(false);
        this.applyVolumes();
      }
    };
    return v.text;
  }

  bark(speaker: string): void {
    const list = this.manifest.barks[speaker];
    if (!list?.length || !this.ctx) return;
    if (this.voiceNode) return;
    this.playFile(list[Math.floor(Math.random() * list.length)], this.voiceBus, 0.9);
  }

  // ------------------------------------------------------------------------------------------- sfx
  /** play a sound effect; `dist` (tiles from camera target) attenuates; throttled per key */
  sfx(key: string, dist = 0, vol = 1, throttle = 0.06): void {
    if (!this.ctx) return;
    const list = this.manifest.sfx[key];
    if (!list?.length) return;
    const now = this.ctx.currentTime;
    if (now - (this.lastPlay.get(key) ?? -1) < throttle) return;
    this.lastPlay.set(key, now);
    const att = 1 / (1 + Math.max(0, dist - 6) * 0.08);
    if (att < 0.04) return;
    this.playFile(list[Math.floor(Math.random() * list.length)], this.sfxBus, vol * att, 0.94 + Math.random() * 0.12);
  }

  private async playFile(file: string, bus: GainNode, vol: number, rate = 1): Promise<void> {
    const buf = await this.load(file);
    if (!buf || !this.ctx) return;
    const g = this.ctx.createGain();
    g.gain.value = vol;
    g.connect(bus);
    const src = this.ctx.createBufferSource();
    src.buffer = buf;
    src.playbackRate.value = rate;
    src.connect(g);
    src.start();
  }

  /** keep a looping ambience at a target volume (0 stops it) */
  async ambient(key: string, target: number): Promise<void> {
    if (!this.ctx) return;
    let l = this.loops.get(key);
    if (!l) {
      if (target <= 0.001) return;
      const f = this.manifest.sfx[key]?.[0];
      if (!f) return;
      this.loops.set(key, null as any);
      const buf = await this.load(f);
      if (!buf || !this.ctx) return;
      const gain = this.ctx.createGain();
      gain.gain.value = 0;
      gain.connect(this.ambBus);
      const src = this.ctx.createBufferSource();
      src.buffer = buf;
      src.loop = true;
      src.connect(gain);
      src.start(0, Math.random() * buf.duration);
      l = { src, gain };
      this.loops.set(key, l);
    }
    if (!l) return;
    l.gain.gain.setTargetAtTime(target, this.ctx.currentTime, 0.6);
  }
}

export const audio = new Audio();
